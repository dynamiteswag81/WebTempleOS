// Generates compiler/consts.js from TempleOS's own headers so the JS compiler
// always uses the exact numeric values TempleOS uses (IC_*, TK_*, RT_*, ...).
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(here, '..', 'vendor', 'TempleOS');
const files = ['Kernel/KernelA.HH', 'Compiler/CompilerA.HH'];
const prefixes = /^(IC_|TK_|RT_|RTF_|RTG_|HTT_|HTt_|HTF_|HTf_|HTG_|ICF_|ICf_|ICG_|CCF_|CCf_|MLF_|MLMF_|GVF_|Ff_|Cf_|KW_|AKW_|PREC_|ASSOC|PRS0|PRS1|PRSF_|FSF_|FSG_|CMT_|CMF_|CM_|OPTf_|OPTF_|MDF_|MDf_|MDG_|IS_|IST_|ECF_|CMPF_|IET_|IEF_|LFSF_|PTR_STARS_NUM|STR_LEN|IC_BODY_SIZE|DOCT_|REGT_|REG_|I8_MIN|CMP_TEMPLATE)/;

const out = new Map();
function evalExpr(e) {
  // Values in these headers are plain ints, hex, shifts, sums of known names.
  let s = e.replace(/\/\/.*$/, '').trim();
  if (!s) return undefined;
  s = s.replace(/\b([A-Za-z_][A-Za-z0-9_]*)\b/g, (m) => {
    if (out.has(m)) return '(' + out.get(m) + 'n)';
    throw new Error('unknown ' + m);
  });
  s = s.replace(/\b(0x[0-9A-Fa-f]+|\d+)\b(?!n)/g, '$1n');
  // eslint-disable-next-line no-eval
  return eval(s);
}
for (const f of files) {
  const txt = fs.readFileSync(path.join(src, f), 'latin1');
  for (const line of txt.split('\n')) {
    const m = /^#define\s+([A-Za-z_][A-Za-z0-9_]*)\s+(.+)$/.exec(line);
    if (!m || !prefixes.test(m[1])) continue;
    try {
      const v = evalExpr(m[2]);
      if (typeof v === 'bigint') out.set(m[1], v.toString());
    } catch (e) { /* non-numeric define, skip */ }
  }
}
let js = '// Generated by tools/gen-consts.js from TempleOS headers. Do not edit.\n';
for (const [k, v] of out) {
  const n = BigInt(v);
  // CCF_ flags exceed 32 bits; keep them BigInt so bit ops stay exact.
  js += (k.startsWith('CCF_') || n > 0x1fffffffffffffn || n < -0x1fffffffffffffn)
    ? `export const ${k}=${v}n;\n` : `export const ${k}=${v};\n`;
}
fs.writeFileSync(path.join(here, '..', 'compiler', 'consts.js'), js);
console.log('wrote', out.size, 'constants');
